import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
await p.goto('http://127.0.0.1:3000/', { waitUntil: 'networkidle' });
await p.getByRole('button', { name: /load northwind scenario/i }).click();
await p.waitForTimeout(800);
await p.screenshot({ path: '.eval/02-scenario.png', fullPage: true });
const ta = await p.locator('textarea').inputValue();
const client = await p.locator('input').first().inputValue();
console.log('ESCALATION:\n' + ta);
console.log('\nCLIENT:', client);
const checked = await p.locator('input[type=checkbox]:checked').evaluateAll(els => els.map(e => e.parentElement.innerText.trim()));
console.log('\nCHECKED SOURCES:', JSON.stringify(checked));
console.log('\nBODY:\n' + (await p.locator('body').innerText()).slice(0, 1500));
await b.close();
